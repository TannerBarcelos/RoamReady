struct CampingAnswer: Sendable {
    let text: String
    /// The answer was given the camper's own checklist steps, so they are listed among the chat's sources.
    var usedChecklist = false
    /// Document passages the model cited, validated against what the request supplied.
    var sources: [DocumentSource] = []
    /// Excerpts the model saw and did not cite.
    var searched: [DocumentSource] = []
    /// The passage the model was shown for each cited or searched source, by source ID.
    var passages: [DocumentSource.ID: String] = [:]
    var coverage: DocumentCoverage = .notSearched
    /// How ready the scope's documents were when this was asked.
    var readiness: ScopeReadiness = .empty
    /// The question was about the booking, so the saved trip is listed beside any document sources.
    var usedSavedTrip = false
    /// The chat turn this answer is, so it can be asked again as of that point. Nil for notices and fixtures.
    var turnID: CampingChatTurn.ID?
}

extension CampingAnswer {
    /// What a question about documents gets when it isn't in English. Nothing is searched or translated.
    static let englishOnlyNotice = CampingAnswer(text: DocumentLanguagePolicy.englishOnlyExplanation)
}

/// Every answer is generated by Apple's on-device model; there are no canned replies.
/// Apple's runtime availability decides eligibility on iPhone, iPad, and Mac (and in Simulator, the host Mac's).
@MainActor
enum CampingAssistant {
    static var globalAvailability: AssistantAvailability {
        #if DEBUG
        if let simulated = uiTestingAvailability { return simulated }
        #endif
        #if canImport(FoundationModels)
        switch SystemLanguageModel.default.availability {
        case .available: return SystemLanguageModel.default.supportsLocale() ? .ready : .unsupportedLanguage
        case .unavailable(let reason):
            switch reason {
            case .deviceNotEligible: return .unsupported
            case .appleIntelligenceNotEnabled: return .disabled
            case .modelNotReady: return .preparing
            @unknown default: return .unavailable
            }
        @unknown default: return .unavailable
        }
        #else
        return .unsupported
        #endif
    }

    /// Whether to offer the chat button and trip/checklist help at all; hidden where Apple Intelligence can't run.
    static var showsChat: Bool { globalAvailability.showsChatButton }

    #if DEBUG
    static var isRunningAssistantUITests: Bool {
        uiTestingAvailability != nil || ProcessInfo.processInfo.arguments.contains("-assistant-device-smoke")
    }

    /// Deterministic UI fixtures, independent of the simulator host’s AI configuration.
    static var uiTestingAvailability: AssistantAvailability? {
        let arguments = ProcessInfo.processInfo.arguments
        guard let index = arguments.firstIndex(of: "-assistant-ui-test"),
              arguments.indices.contains(index + 1) else { return nil }
        switch arguments[index + 1] {
        case "ready": return .ready
        case "disabled": return .disabled
        case "preparing": return .preparing
        case "unsupported": return .unsupported
        case "unavailable": return .unavailable
        case "unsupported-language": return .unsupportedLanguage
        default: return nil
        }
    }
    #endif

    /// One clear status line; every Apple unavailability reason maps to its own explanation.
    static var availability: String {
        #if canImport(FoundationModels)
        switch SystemLanguageModel.default.availability {
        case .available: return "Apple on-device AI available · Works offline"
        case .unavailable(let reason):
            switch reason {
            case .deviceNotEligible: return "This device doesn’t support Apple Intelligence"
            case .appleIntelligenceNotEnabled: return "Turn on Apple Intelligence in Settings to use AI help"
            case .modelNotReady: return "Apple’s AI model is still downloading or preparing. Try again later."
            @unknown default: return "Apple AI is currently unavailable"
            }
        @unknown default: return "Apple AI is currently unavailable"
        }
        #else
        return "Apple AI requires a supported system version"
        #endif
    }

    /// A new conversation: its own model session, made on the first question.
    static func makeChat() -> CampingChat {
        #if DEBUG
        if let generator = uiTestGenerator { return CampingChat(model: SingleTurnChatModel(generator)) }
        #endif
        #if canImport(FoundationModels)
        return CampingChat(model: AppleCampingChatModel(), counter: AppleTokenCounter())
        #else
        return CampingChat(model: SingleTurnChatModel(UnavailableGenerator()))
        #endif
    }

    /// Trip and checklist help pass their matching saved steps as context; general chat uses the active rig's.
    /// The question is the next turn of `chat`; `before` asks again as of an earlier turn.
    /// Model failures reach the UI as retryable errors rather than being replaced with saved text.
    static func answer(question: String, steps candidates: [ChecklistStepDraft], rigType: RigType?, step: ChecklistStepDraft?,
                       scope: CampingHelpRequest.Scope = .checklist, chat: CampingChat, chatScope: AnyHashable,
                       before turnID: CampingChatTurn.ID? = nil,
                       rigContext: CampingRigContext? = nil, documents: DocumentEvidence? = nil,
                       tripFacts: TripBookingFacts? = nil,
                       onStage: (@MainActor (AssistantStage) -> Void)? = nil) async throws -> CampingAnswer {
        try Task.checkCancellation()
        let request = CampingHelpRequest(question: question, steps: candidates, rigType: rigType, step: step, scope: scope,
                                         previousQuestion: chat.previousQuestion(in: chatScope, before: turnID),
                                         rigContext: rigContext, documents: documents, tripFacts: tripFacts)
        let reply: CampingReply
        do {
            try Task.checkCancellation()
            onStage?(.writing)
            reply = try await chat.answer(request, in: chatScope, before: turnID)
        } catch is CancellationError {
            throw CancellationError()
        } catch {
            throw (error as? CampingChatFailure) ?? .failed
        }
        return CampingAnswer(text: reply.text, usedChecklist: !request.passages.isEmpty,
                             sources: reply.sources, searched: reply.searched, passages: reply.passages,
                             coverage: reply.coverage, readiness: reply.readiness,
                             usedSavedTrip: reply.usedSavedTrip, turnID: reply.turnID)
    }

    #if !canImport(FoundationModels)
    private struct UnavailableGenerator: CampingResponseGenerating {
        func respond(to prompt: String, instructions: String) async throws -> String { throw CampingChatFailure.notReady }
    }
    #endif

    #if DEBUG
    private struct UITestGenerator: CampingResponseGenerating {
        let fails: Bool
        /// Answers from the first supplied excerpt and cites it, the way a grounded model would.
        var citesDocuments = false
        /// Waits before answering the first question only, so a test can close the sheet or retry mid-request.
        var delaysFirstCall = false
        /// Fails the first question only, so Retry can succeed.
        var failsFirstCall = false
        /// Waits before every answer, so a UI test can resize or rotate while it's generating.
        var delay: Duration = .zero
        func respond(to prompt: String, instructions: String) async throws -> String {
            CampingAssistant.uiTestCalls += 1
            let isFirst = CampingAssistant.uiTestCalls == 1
            if delaysFirstCall && isFirst { try await Task.sleep(for: .seconds(3)) }
            if delay > .zero { try await Task.sleep(for: delay) }
            if fails || (failsFirstCall && isFirst) { throw CampingChatFailure.failed }
            if citesDocuments {
                return prompt.contains("\n[S1] ")
                    ? "Per your manual, error code E4 means the water heater igniter failed to light. Turn the unit off and wait five minutes before retrying. [S1]"
                    : (instructions.contains("could not be searched")
                        ? "A document isn't ready yet, so I can't support an answer about that from it yet."
                        : "Your documents don't cover that.")
            }
            return "Test response: keep drinking water in a clean, covered container."
        }
    }

    fileprivate static var uiTestCalls = 0

    private static var uiTestGenerator: UITestGenerator? {
        guard uiTestingAvailability == .ready else { return nil }
        let arguments = ProcessInfo.processInfo.arguments
        guard let index = arguments.firstIndex(of: "-assistant-generation-test"),
              arguments.indices.contains(index + 1) else { return nil }
        switch arguments[index + 1] {
        case "reply": return UITestGenerator(fails: false)
        case "slow-reply": return UITestGenerator(fails: false, delay: .seconds(4))
        case "failure": return UITestGenerator(fails: true)
        case "document": return UITestGenerator(fails: false, citesDocuments: true)
        case "slow": return UITestGenerator(fails: false, delaysFirstCall: true)
        case "failure-once": return UITestGenerator(fails: false, failsFirstCall: true)
        default: return nil
        }
    }
    #endif

}
